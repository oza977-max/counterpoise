// R18-F (specs/intake-flow.md §27.11). The pure scorer: derived QUESTION_FIELDS, the overlay and the
// per-case scoring, checked against the REAL corpus (backtest/cases.json) and the engine's recorded
// verdicts (backtest/engine-verdicts.json). Nothing in the corpus is invented here.

let policy: PolicyFile;
let packs: JurisdictionPack[];
interface Case {
  id: string;
  title: string;
  prose: string;
  graph: CorpusGraph;
}
const CASES: Case[] = JSON.parse(readFileSync(resolve(__dirname, '../../backtest/cases.json'), 'utf-8')).cases;
const EXPECTED: Record<string, { status: string; tier: string }> = JSON.parse(
  readFileSync(resolve(__dirname, '../../backtest/engine-verdicts.json'), 'utf-8'),
).verdicts;

// Loaded at module level: the drift cases below are built from the policy while the tests are collected.
{
  const r = loadPolicy(readFileSync(resolve(__dirname, '../../policy/appetite.yaml'), 'utf-8'));
  if (!r.valid) throw new Error('policy invalid');
  policy = r.policy;
  const p = loadPacks(getPackSources());
  if (p.errors.length > 0) throw new Error('pack errors');
  packs = p.packs;
}

const gold = (id: string): DataFlowGraph => {
  const c = CASES.find((x) => x.id === id)!;
  return corpusGraph(c.id, c.graph);
};
const fill = (entries: Record<string, string[]>): Prefill =>
  new Map(
    Object.entries(entries).map(([q, opts]) => [
      q as QuestionId,
      { values: opts.map((option) => ({ option, quote: 'two words' })) },
    ]),
  );
const score = (id: string, prefill: Prefill | null) =>
  scoreCase({ gold: gold(id), prefill, expected: EXPECTED[id]!, policy, packs });

