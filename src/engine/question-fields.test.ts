const workedFile = JSON.parse(readFileSync(resolve(__dirname, '../../backtest/worked-case-answers.json'), 'utf-8')) as {
  cases: Record<string, { answers: Record<string, string | string[]> }>;
};

// Test-only: recover the option key from the blind answers' words, as backtest-parity.test.ts does.
function resolveKey(id: QuestionId, text: string): string {
  if (findQuestion(id)?.freeText) return text;
  const staticKey = optionKeyForText(id, text);
  if (staticKey) return staticKey;
  const byName = (list: { id?: string; code?: string; plain_name?: string; name?: string; kind?: string }[] | undefined, pick: (e: never) => boolean) =>
    (list ?? []).find(pick as never);
  if (id === '3') {
    const p = byName(policy.platforms, (e: { plain_name?: string }) => e.plain_name === text);
    if (p?.id) return p.id;
  }
  if (id === '3supplier') {
    const v = (policy.vendors ?? []).find((x) => (x.kind ?? 'supplier') === 'supplier' && x.plain_name === text);
    if (v) return v.id;
  }
  if (id === '3aWhich') {
    const v = (policy.vendors ?? []).find((x) => x.kind === 'company_assistant' && x.plain_name === text);
    if (v) return v.id;
  }
  if (id === '11') {
    const j = (policy.jurisdictions ?? []).find((x) => x.name === text);
    if (j) return j.code;
  }
  throw new Error(`no key for Q${id} "${text}"`);
}

function resolveAnswers(raw: Record<string, string | string[]>): PlainAnswers {
  const out: PlainAnswers = {};
  for (const [qid, value] of Object.entries(raw)) {
    const id = qid as QuestionId;
    out[id] = Array.isArray(value) ? value.map((v) => resolveKey(id, v)) : resolveKey(id, value);
  }
  return out;
}

const graphOf = (answers: PlainAnswers): DataFlowGraph => {
  let n = 0;
  return buildGraphFromForm(plainAnswersToFormValues(answers, policy).values, '2026-01-01T00:00:00Z', () => `id-${++n}`);
};

/** A graph's values for the given fields, flattened and sorted, for comparison. */
function fieldView(graph: DataFlowGraph, fields: readonly string[]): Record<string, string[]> {
  const gf = goldFieldsOf(graph) as Record<string, unknown[]>;
  return Object.fromEntries(fields.map((f) => [f, (gf[f] ?? []).map((v) => JSON.stringify(v)).sort()]));
}

/** Everything of the answers that a pre-fill could carry: the select questions, one value or the ticks. */
function prefillOf(answers: PlainAnswers): Prefill {
  const out: Prefill = new Map();
  for (const q of QUESTION_STRUCTURE) {
    if (q.kind === 'free') continue;
    const v = answers[q.id];
    if (v === undefined || (Array.isArray(v) && v.length === 0)) continue;
    out.set(q.id, { values: (Array.isArray(v) ? v : [v]).map((option) => ({ option, quote: 'two words' })) });
  }
  return out;
}

describe('applyPrefillToGraph agrees with buildGraphFromForm (drift test, §27.11)', () => {
  // A DIFFERENT starting graph, so an overlay that did nothing could not pass by accident.
  const START_ANSWERS: PlainAnswers = {
    '1': 'Start', '2': 'Start', '3': 'not-sure', '4': 'agentic', '5': ['public'], '6': 'acts-alone', '6b': 'trades',
    '7': 'public-market', '8': 'trading', '9': 'no', '10': 'wide', '11': ['elsewhere-not-sure'], '12': 'yes',
    '13': ['credentialed'], '14': 'yes',
  };

  const subjects: { name: string; answers: PlainAnswers }[] = [
    ...WORKED_EXAMPLES.map((e) => ({ name: `example ${e.id}`, answers: e.answers })),
    ...Object.entries(workedFile.cases).map(([id, c]) => ({ name: `worked case ${id}`, answers: resolveAnswers(c.answers) })),
  ];

  it('covers the 10 scripted examples and the 9 worked cases', () => {
    expect(WORKED_EXAMPLES).toHaveLength(10);
    expect(Object.keys(workedFile.cases)).toHaveLength(9);
  });

  it.each(subjects.map((s) => [s.name, s.answers] as const))(
    'TC-R18-GI-12-07: overlaying all of %s answers onto another graph gives the form\'s own values on every QUESTION_FIELDS field',
    (_name, answers) => {
      // A model never fills a free-text answer (they are not in the catalogue), so the form's side is built
      // without them too: the typed supplier name and the typed "other" decision are the only values the
      // overlay cannot carry, by design.
      const { '3supplierName': _a, '8other': _b, '3model': _c, ...selectAnswers } = answers;
      void [_a, _b, _c];
      const want = graphOf(selectAnswers);
      const prefill = prefillOf(answers);
      const got = applyPrefillToGraph(graphOf(START_ANSWERS), prefill, policy);
      const fields = new Set<string>();
      for (const id of prefill.keys()) {
        const e = questionFields(policy).get(id);
        if (e && e.scored) for (const f of e.fields) fields.add(f);
      }
      expect(fields.size).toBeGreaterThan(5);
      const list = [...fields].sort();
      expect(fieldView(got, list)).toEqual(fieldView(want, list));
      // and the test can fail: the starting graph alone does not already agree
      expect(fieldView(graphOf(START_ANSWERS), list)).not.toEqual(fieldView(want, list));
    },
  );
});

// ---- TC-R18-GI-12-05: the scoring table is deterministic and its counts add up ----

describe('TC-R18-GI-12-05: the scoring table (properties)', () => {
  const selectQuestions = QUESTION_STRUCTURE.filter((q) => q.kind !== 'free');
  // A canned reply: for each question, absent or a real option (a tick-all question: one or two).
  const prefillArb: fc.Arbitrary<Prefill | null> = fc.option(
    fc
      .tuple(
        ...selectQuestions.map((q) => {
          const keys = allOptionKeys(q, policy);
          const picks =
            q.kind === 'multi'
              ? fc.uniqueArray(fc.constantFrom(...keys), { minLength: 1, maxLength: 2 })
              : fc.constantFrom(...keys).map((k) => [k]);
          return fc.option(picks, { nil: undefined });
        }),
      )
      .map((picked) => {
        const m: Prefill = new Map();
        picked.forEach((opts, i) => {
          if (opts) m.set(selectQuestions[i]!.id, { values: opts.map((option) => ({ option, quote: 'two words' })) });
        });
        return m;
      }),
    { nil: null },
  );
  const runArb = fc.array(fc.tuple(fc.constantFrom(...CASES.map((c) => c.id)), prefillArb), { minLength: 0, maxLength: 8 });
  const scoreAll = (run: [string, Prefill | null][]) => run.map(([id, p]) => score(id, p));

  it('scoring twice gives a byte-identical table', () => {
    fc.assert(
      fc.property(runArb, (run) => {
        expect(JSON.stringify(tallyScores(scoreAll(run)))).toBe(JSON.stringify(tallyScores(scoreAll(run))));
        expect(JSON.stringify(scoreAll(run))).toBe(JSON.stringify(scoreAll(run)));
      }),
      { numRuns: 40 },
    );
  });

  it('right + blank + wrong equals the number of cases in which the question was scored, and verdict matches lie between 0 and the cases run', () => {
    fc.assert(
      fc.property(runArb, (run) => {
        const scores = scoreAll(run);
        const t = tallyScores(scores);
        for (const [q, c] of Object.entries(t.perQuestion)) {
          const asked = scores.filter((s) => s.questions[q] !== 'not scored' && s.questions[q] !== undefined).length;
          expect(c.right + c.blank + c.wrong, q).toBe(asked);
        }
        expect(t.verdictMatches).toBeGreaterThanOrEqual(0);
        expect(t.verdictMatches).toBeLessThanOrEqual(run.length);
        expect(t.verdictMatches + t.noAnswer).toBeLessThanOrEqual(run.length);
      }),
      { numRuns: 40 },
    );
  });

  it('reordering the cases (and their replies) does not change any count', () => {
    fc.assert(
      fc.property(runArb, (run) => {
        const forward = tallyScores(scoreAll(run));
        const backward = tallyScores(scoreAll([...run].reverse()));
        expect(JSON.stringify(backward)).toBe(JSON.stringify(forward));
      }),
      { numRuns: 40 },
    );
  });

  it('the counterexample strategies hold: all replies blank, all wrong, one reply, a duplicated reply, a run of 0 and of 30 cases', () => {
    const ids = CASES.map((c) => c.id);
    const empty = tallyScores([]);
    expect(empty).toEqual({ perQuestion: {}, verdictMatches: 0, noAnswer: 0 });
    const allBlank = tallyScores(ids.map((id) => score(id, null)));
    expect(allBlank.verdictMatches).toBe(0);
    expect(allBlank.noAnswer).toBe(31);
    for (const c of Object.values(allBlank.perQuestion)) expect(c.right + c.wrong).toBe(0);
    const everyWrong = tallyScores(ids.map((id) => score(id, fill({ '12': ['not-sure'], '9': ['not-sure'] }))));
    expect(everyWrong.perQuestion['9']!.right).toBe(0);
    const thirty = tallyScores(ids.slice(0, 30).map((id) => score(id, fill({}))));
    expect(thirty.verdictMatches).toBe(30);
    const one = tallyScores([score('A-01', fill({ '12': ['no'] }))]);
    expect(one.perQuestion['12']).toEqual({ right: 1, blank: 0, wrong: 0 });
    const twice = tallyScores([score('A-01', fill({ '12': ['no'] })), score('A-01', fill({ '12': ['no'] }))]);
    expect(twice.perQuestion['12']).toEqual({ right: 2, blank: 0, wrong: 0 });
  });
});
