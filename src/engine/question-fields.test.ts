// ---- the scorer table, on real cases ----

describe('scoring one case (TC-R18-GI-12-08, TC-R18-MS-8-03)', () => {
  it('TC-R18-GI-12-08: a question the form cannot express for a case is "not scored", never "wrong", and adds nothing to the overlay', () => {
    // A-01's gold has vendor `internal` with Zone B; "built by a team in your firm" gives Zone C, so no Q3 option reproduces it.
    expect(optionsReproducing('3', goldFieldsOf(gold('A-01')), QUESTION_STRUCTURE, policy)).toEqual([]);
    const s = score('A-01', fill({ '3': ['firm-built'] }));
    expect(s.questions['3']).toBe('not scored');
    expect(s.questions['3']).not.toBe('wrong');
    const overlaid = applyPrefillToGraph(gold('A-01'), fill({ '3': ['firm-built'] }), policy, new Set());
    expect(JSON.stringify(overlaid)).not.toContain('Zone C');
    expect(overlaid).toEqual(gold('A-01'));
    // and the verdict was not harmed by a fill the form could not express
    expect(s.verdict).toBe('matched');
  });

  it('a case whose gold exactly one option reproduces is scored right or wrong as usual', () => {
    const c = CASES.find((x) => {
      const r = optionsReproducing('3', goldFieldsOf(corpusGraph(x.id, x.graph)), QUESTION_STRUCTURE, policy);
      return r.length === 1 && r[0] === 'firm-built';
    });
    expect(c, 'a corpus case a firm-built Q3 reproduces').toBeDefined();
    expect(score(c!.id, fill({ '3': ['firm-built'] })).questions['3']).toBe('right');
    expect(score(c!.id, fill({ '3': ['not-sure'] })).questions['3']).toBe('wrong');
    expect(score(c!.id, fill({})).questions['3']).toBe('blank');
  });

  it('a question with several reproducing options is not scored (Question 10 on an at-scale gold: both "team" and "wide" give it)', () => {
    const atScale = CASES.find((c) => c.graph.output.scale === 'at_scale')!;
    expect(score(atScale.id, fill({ '10': ['wide'] })).questions['10']).toBe('not scored');
  });

  it('TC-R18-MS-8-03: a fill whose resulting verdict equals the recorded one is "matched"; one that changes it is "did not match"; the model\'s own claim is never read', () => {
    const base = gold('A-01');
    // The independent oracle: edit the gold graph by hand and run the engine, then compare with the case's recorded verdict.
    const handEdited = JSON.parse(JSON.stringify(base)) as DataFlowGraph;
    (handEdited.output_nodes[0] as unknown as Record<string, unknown>).exposure = 'market-facing';
    (handEdited.output_nodes[0] as unknown as Record<string, unknown>).output_reversibility = 'irreversible';
    const hand = scoreCase({ gold: handEdited, prefill: fill({}), expected: EXPECTED['A-01']!, policy, packs });
    expect(hand.verdict, 'the hand edit must change A-01 verdict for this test to mean anything').toBe('did not match');

    const right = score('A-01', fill({ '7': ['other-teams'], '9': ['yes'], '4': ['language'], '12': ['no'] }));
    expect(right.verdict).toBe('matched');
    expect(Object.values(right.questions).filter((v) => v === 'right')).toHaveLength(4);

    const wrong = score('A-01', fill({ '7': ['public-market'], '9': ['no'] }));
    expect(wrong.questions['7']).toBe('wrong');
    expect(wrong.questions['9']).toBe('wrong');
    expect(wrong.verdict).toBe('did not match');
    expect(wrong.verdict).not.toMatch(/^matched/);
  });

  it('no usable answer scores every scored question blank and the verdict "no answer"', () => {
    const s = score('A-01', null);
    expect(s.verdict).toBe('no answer');
    expect(Object.values(s.questions).filter((v) => v === 'wrong' || v === 'right')).toEqual([]);
    expect(Object.values(s.questions).filter((v) => v === 'blank').length).toBeGreaterThan(0);
  });

  it('an answer that fills nothing leaves the gold graph untouched, so every corpus case reproduces its recorded verdict (the control)', () => {
    for (const c of CASES) {
      expect(score(c.id, fill({})).verdict, c.id).toBe('matched');
    }
  });
});

